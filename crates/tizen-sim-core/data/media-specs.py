"""Generates media.toml: the media formats each Tizen TV year lists.

Reads Samsung's TV video specification pages, one per year, saved as HTML in
a folder as <folder>/<year>-tv-video-specifications.html (2017 to 2026),
from https://developer.samsung.com/smarttv/develop/specifications/
media-specifications/<year>-tv-video-specifications.html. The Music table of
.../specifications/media-specifications.html is transcribed below (MUSIC).
Each year's page has one table
per model group; a codec every group lists is listed plainly, one only some
groups list goes under `some_models`.

Only containers and codecs a web App can name in a MIME type are kept (see
shims/src/media.ts); the rest (VOB, RealVideo, DivX...) are dropped.

Usage: python3 media-specs.py <folder> > media.toml
"""

import html
import os
import re
import sys

YEARS = {2017: "3.0", 2018: "4.0", 2019: "5.0", 2020: "5.5", 2021: "6.0",
         2022: "6.5", 2023: "7.0", 2024: "8.0", 2025: "9.0", 2026: "10.0"}

CONTAINERS = {"MP4": "MP4", "MOV": "MOV", "3GP": "3GP", "MKV": "MKV", "TS": "MPEG-TS",
              "AVI": "AVI", "ASF": "ASF", "FLV": "FLV", "PS": "MPEG-PS", "WebM": "WebM"}

# (substring of the table's name, name used here); first match wins.
VIDEO = [("h.264", "H.264"), ("hevc", "HEVC"), ("av1", "AV1"), ("vp9", "VP9"),
         ("vp8", "VP8"), ("microsoft mpeg-4", None), ("mpeg-4", "MPEG-4 Part 2")]
AUDIO = [("he-aac", "HE-AAC"), ("aac", "AAC"), ("ac-4", "AC-4"), ("ac4", "AC-4"),
         ("dd+", "E-AC-3"), ("ac-3", "AC-3"), ("ac3", "AC-3"), ("mp3", "MP3"),
         ("mpeg-h", "MPEG-H"), ("opus", "Opus"), ("vorbis", "Vorbis"), ("dts", "DTS")]

# The index's Music table: format and codec. It has no years; its notes say
# WMA is gone from 24TV_BASIC4 and from 2025 on.
MUSIC = [("MP3", "MP3"), ("MP4", "AAC"), ("AAC", "AAC"), ("FLAC", "FLAC"),
         ("Ogg", "Vorbis"), ("WAV", "LPCM"), ("WMA", "WMA")]


def text(cell):
    cell = re.sub(r"<br\s*/?>", " | ", cell)
    return " ".join(html.unescape(re.sub(r"<[^>]+>", " ", cell)).split())


def split(value):
    return [part.strip() for part in value.split("|") if part.strip()]


def name(value, table):
    lowered = value.lower().replace(" ", "")
    for key, named in table:
        if key.replace(" ", "") in lowered:
            return named
    return None


def rows(table):
    """The table's body rows, with rowspan cells repeated into each row."""
    grid, pending = [], {}
    for row in re.findall(r"<tr.*?</tr>", table, re.S)[1:]:
        cells = re.findall(r"<t[hd]([^>]*)>(.*?)</t[hd]>", row, re.S)
        out, column, i = [], 0, 0
        while i < len(cells) or column in pending:
            if column in pending:
                left, value = pending[column]
                out.append(value)
                if left <= 1:
                    del pending[column]
                else:
                    pending[column] = (left - 1, value)
            else:
                attributes, cell = cells[i]
                i += 1
                value = text(cell)
                span = re.search(r'rowspan="?(\d+)', attributes)
                if span and int(span.group(1)) > 1:
                    pending[column] = (int(span.group(1)) - 1, value)
                out.append(value)
            column += 1
        grid.append(out)
    return grid


def model_groups(page):
    """(model group, {container: (video codecs, audio codecs)}) per table."""
    groups = []
    for match in re.finditer(r"<h[2-4][^>]*>(.*?)</h[2-4]>(.*?)(?=<h[2-4]|$)", page, re.S):
        tables = re.findall(r"<table.*?</table>", match.group(2), re.S)
        if not tables:
            continue
        formats = {}
        for row in rows(tables[0]):
            if len(row) < 7:
                continue
            video = name(row[2], VIDEO)
            audio = {name(a, AUDIO) for a in split(row[6])} - {None}
            for container in split(row[1]):
                if container not in CONTAINERS:
                    continue
                v, a = formats.setdefault(CONTAINERS[container], (set(), set()))
                if video:
                    v.add(video)
                a.update(audio)
        groups.append((text(match.group(1)), formats))
    return groups


def toml_list(values):
    return "[" + ", ".join('"%s"' % v for v in values) + "]"


def main(folder):
    print("# Generated by media-specs.py from Samsung's TV media specifications; do not edit")
    print("# by hand. Per Version Profile: the containers and codecs its TV year lists that a")
    print("# web App can name. `some_models` lists a codec only some of the year's model groups")
    print("# list, with those groups. `music` formats come from the media specifications")
    print("# index's Music table, which has no years.")
    for year, version in YEARS.items():
        with open(os.path.join(folder, "%d-tv-video-specifications.html" % year), encoding="utf-8") as f:
            groups = model_groups(f.read())
        names = [group for group, _ in groups]
        containers = sorted({c for _, formats in groups for c in formats})
        # Formats with the same codecs share an entry.
        entries = {}
        some = {}
        for container in containers:
            every, anyone = None, set()
            for group, formats in groups:
                video, audio = formats.get(container, (set(), set()))
                codecs = video | audio
                every = codecs if every is None else every & codecs
                anyone |= codecs
                for codec in codecs:
                    some.setdefault(codec, set()).add(group)
            entries.setdefault(tuple(sorted(every)), []).append(container)
        print()
        print("[[tv]]")
        print('profile = "%s"' % version)
        print("year = %d" % year)
        print('page = "specifications/media-specifications/%d-tv-video-specifications.html"' % year)
        print("model_groups = %s" % toml_list(names))
        partial = {c: sorted(g) for c, g in some.items() if len(g) < len(names)}
        for codecs, members in entries.items():
            print()
            print("[[tv.format]]")
            print("containers = %s" % toml_list(members))
            listed = sorted(set(codecs) | {c for c in partial if any(
                c in formats.get(m, (set(), set()))[0] | formats.get(m, (set(), set()))[1]
                for _, formats in groups for m in members)})
            print("codecs = %s" % toml_list(listed))
        for container, codec in MUSIC:
            if codec == "WMA" and year >= 2025:
                continue
            print()
            print("[[tv.format]]")
            print('containers = ["%s"]' % container)
            print('codecs = ["%s"]' % codec)
            print("music = true")
        if year == 2024:
            partial["WMA"] = [g for g in names if not g.startswith("24TV_BASIC4")]
        if partial:
            print()
            print("[tv.some_models]")
            for codec, members in sorted(partial.items()):
                print('"%s" = %s' % (codec, toml_list(members)))


if __name__ == "__main__":
    main(sys.argv[1])
